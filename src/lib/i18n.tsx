const ALL_MESSAGES: Record<AppLocale, Record<MessageKey, string>> = {
  en: EN_MESSAGES,
  es: ES_MESSAGES,
  he: HE_MESSAGES,
};

function detectInitialLocale(): AppLocale {
  try {
    const saved =
      window.localStorage.getItem(LOCALE_STORAGE_KEY) ||
      window.localStorage.getItem(LEGACY_LOCALE_STORAGE_KEY);
    if (saved === 'en' || saved === 'es' || saved === 'he') {
      return saved;
    }
    const browserLang = (navigator.language || '').toLowerCase();
    if (browserLang.startsWith('he') || browserLang.startsWith('iw')) return 'he';
    if (browserLang.startsWith('es')) return 'es';
  } catch {
    // Ignore storage access restrictions
  }
  return 'en';
}

export interface I18nContextValue {
  locale: AppLocale;
  dir: TextDirection;
  isRtl: boolean;
  bcp47: string;
  setLocale: (next: AppLocale) => void;
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
  tPurpose: (purpose: TripPurpose) => string;
  tLocationCategory: (category: LocationCategory) => string;
  tExpenseCategory: (category: ExpenseCategory) => string;
  tStage: (stage: TripStageKey) => string;
  monthLabels: readonly string[];
  formatLocalizedDate: (isoDate: string) => string;
  formatLocalizedClock: (timestampMs: number) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<AppLocale>(() => detectInitialLocale());

  const option = useMemo(
    () => LOCALE_OPTIONS.find((opt) => opt.value === locale) ?? LOCALE_OPTIONS[0],
    [locale]
  );

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = option.dir;
    try {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
    } catch {
      // Ignore storage failures
    }
  }, [locale, option.dir]);

  const setLocale = useCallback((next: AppLocale) => {
    setLocaleState(next);
  }, []);

  const t = useCallback(
    (key: MessageKey, vars?: Record<string, string | number>): string => {
      const table = ALL_MESSAGES[locale] ?? EN_MESSAGES;
      let text = table[key] ?? EN_MESSAGES[key] ?? key;
      if (vars) {
        for (const [varName, val] of Object.entries(vars)) {
          text = text.replace(new RegExp(`\\{${varName}\\}`, 'g'), String(val));
        }
      }
      return text;
    },
    [locale]
  );

  const tPurpose = useCallback(
    (purpose: TripPurpose): string => PURPOSE_LABELS[locale]?.[purpose] ?? purpose,
    [locale]
  );

  const tLocationCategory = useCallback(
    (category: LocationCategory): string =>
      LOCATION_CATEGORY_LABELS[locale]?.[category] ?? category,
    [locale]
  );

  const tExpenseCategory = useCallback(
    (category: ExpenseCategory): string => EXPENSE_CATEGORY_LABELS[locale]?.[category] ?? category,
    [locale]
  );

  const tStage = useCallback(
    (stage: TripStageKey): string => STAGE_LABELS[locale]?.[stage] ?? stage,
    [locale]
  );

  const formatLocalizedDate = useCallback(
    (isoDate: string): string => {
      if (!isoDate) return '';
      const parts = isoDate.split('-').map(Number);
      if (parts.length !== 3 || parts.some((n) => Number.isNaN(n))) return isoDate;
      const dt = new Date(parts[0], parts[1] - 1, parts[2]);
      return dt.toLocaleDateString(option.bcp47, {
        month: 'short',
        day: 'numeric',
        year: 'numeric',
      });
    },
    [option.bcp47]
  );

  const formatLocalizedClock = useCallback(
    (timestampMs: number): string =>
      new Date(timestampMs).toLocaleTimeString(option.bcp47, {
        hour: 'numeric',
        minute: '2-digit',
      }),
    [option.bcp47]
  );

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      dir: option.dir,
      isRtl: option.dir === 'rtl',
      bcp47: option.bcp47,
      setLocale,
      t,
      tPurpose,
      tLocationCategory,
      tExpenseCategory,
      tStage,
      monthLabels: MONTH_SHORT_LABELS[locale],
      formatLocalizedDate,
      formatLocalizedClock,
    }),
    [
      locale,
      option.dir,
      option.bcp47,
      setLocale,
      t,
      tPurpose,
      tLocationCategory,
      tExpenseCategory,
      tStage,
      formatLocalizedDate,
      formatLocalizedClock,
    ]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error('useI18n must be used within an I18nProvider');
  }
  return ctx;
}
